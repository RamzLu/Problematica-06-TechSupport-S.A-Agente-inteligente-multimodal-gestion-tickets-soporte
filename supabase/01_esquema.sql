create or replace function public.crear_ticket_con_historial(p_datos jsonb, p_usuario text)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  v_ticket public.tickets;
begin
  insert into public.tickets (solicitante, organizacion_id, area, titulo, descripcion, categoria, prioridad)
  values (
    p_usuario,
    p_datos ->> 'organizacion_id',
    p_datos ->> 'area',
    p_datos ->> 'titulo',
    p_datos ->> 'descripcion',
    p_datos ->> 'categoria',
    p_datos ->> 'prioridad'
  )
  returning * into v_ticket;

  insert into public.ticket_historial (ticket_id, usuario, tipo, detalle)
  values (v_ticket.id, p_usuario, 'Creacion', 'Ticket creado');

  return to_jsonb(v_ticket);
end;
$$;

create or replace function public.aplicar_cambio_ticket(
  p_ticket_id bigint, p_campos jsonb, p_usuario text, p_tipo text, p_detalle text)
returns jsonb
language plpgsql
set search_path = ''
as $$
declare
  v_evento public.ticket_historial;
begin
  update public.tickets t set
    estado      = coalesce(p_campos ->> 'estado', t.estado),
    prioridad   = coalesce(p_campos ->> 'prioridad', t.prioridad),
    responsable = case when p_campos ? 'responsable' then p_campos ->> 'responsable' else t.responsable end,
    adjuntos    = case when p_campos ? 'adjuntos'
                       then array(select jsonb_array_elements_text(p_campos -> 'adjuntos'))
                       else t.adjuntos end
  where t.id = p_ticket_id;

  if not found then
    raise exception 'ticket_inexistente';
  end if;

  insert into public.ticket_historial (ticket_id, usuario, tipo, detalle)
  values (p_ticket_id, p_usuario, p_tipo, p_detalle)
  returning * into v_evento;

  return to_jsonb(v_evento);
end;
$$;

revoke all on function public.crear_ticket_con_historial(jsonb, text) from public, anon, authenticated;
revoke all on function public.aplicar_cambio_ticket(bigint, jsonb, text, text, text) from public, anon, authenticated;
grant execute on function public.crear_ticket_con_historial(jsonb, text) to service_role;
grant execute on function public.aplicar_cambio_ticket(bigint, jsonb, text, text, text) to service_role;
