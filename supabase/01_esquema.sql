);

create or replace function public.crear_perfil_para_nuevo_usuario()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  meta jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  rol_meta text := coalesce(nullif(meta ->> 'rol', ''), 'usuario');
begin
  if rol_meta not in ('usuario', 'soporte') then
    rol_meta := 'usuario';
  end if;

  insert into public.profiles (id, codigo, nombre, email, rol, organizacion_id, area, cargo)
  values (
    new.id,
    coalesce(
      nullif(meta ->> 'codigo', ''),
      case when rol_meta = 'soporte' then 's' else 'u' end
        || lpad(nextval('public.seq_codigo_usuario')::text, 3, '0')
    ),
    coalesce(nullif(meta ->> 'nombre', ''), split_part(new.email, '@', 1)),
    lower(new.email),
    rol_meta,
    coalesce(nullif(meta ->> 'organizacion_id', ''), 'org_central'),
    coalesce(nullif(meta ->> 'area', ''), 'General'),
    coalesce(meta ->> 'cargo', '')
  );
  return new;
end;
$$;

revoke all on function public.crear_perfil_para_nuevo_usuario() from public, anon, authenticated;

drop trigger if exists al_crear_usuario_auth on auth.users;
create trigger al_crear_usuario_auth
  after insert on auth.users
  for each row execute function public.crear_perfil_para_nuevo_usuario();

create table if not exists public.tickets (
  id              bigint generated by default as identity (start with 1055) primary key,
  creado          timestamptz not null default now(),
  solicitante     text not null references public.profiles (codigo) on update cascade,
  organizacion_id text not null default 'org_central'
                    references public.organizaciones (id) on update cascade,
  area            text not null default 'General',
  titulo          text not null check (char_length(titulo) between 5 and 200),
  descripcion     text not null check (char_length(descripcion) between 10 and 2000),
  categoria       text not null check (categoria in (
                    'Hardware', 'Software', 'Redes y conectividad',
                    'Sistemas y aplicaciones', 'Accesos y permisos',
                    'Infraestructura', 'Otros')),
  prioridad       text not null check (prioridad in ('Baja', 'Media', 'Alta', 'Critica')),
  estado          text not null default 'Abierto' check (estado in (
                    'Abierto', 'En revision', 'En progreso',
                    'Pendiente', 'Resuelto', 'Cerrado')),
  responsable     text references public.profiles (codigo) on update cascade on delete set null,
  adjuntos        text[] not null default '{}'
);

create index if not exists tickets_solicitante_idx on public.tickets (solicitante);
create index if not exists tickets_estado_idx on public.tickets (estado);

create table if not exists public.ticket_historial (
  id         bigint generated always as identity primary key,
  ticket_id  bigint not null references public.tickets (id) on delete cascade,
  fecha      timestamptz not null default now(),
  usuario    text not null references public.profiles (codigo) on update cascade,
  tipo       text not null check (tipo in (
               'Creacion', 'Cambio de estado', 'Cambio de prioridad', 'Comentario',
               'Archivo', 'Asignacion', 'Reasignacion')),
  detalle    text not null
);

create index if not exists ticket_historial_ticket_idx on public.ticket_historial (ticket_id, id);

